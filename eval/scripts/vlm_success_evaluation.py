def run_evaluation(args: argparse.Namespace) -> tuple[Path, dict[str, Any]]:
    if args.max_parse_retries < 0:
        raise ValueError("--max-parse-retries cannot be negative")
    if args.limit_trajectories is not None and args.limit_trajectories < 1:
        raise ValueError("--limit-trajectories must be positive")
    if not math.isfinite(args.sampling_fps) or args.sampling_fps <= 0:
        raise ValueError("--sampling-fps must be finite and positive")
    if args.max_frames < 1:
        raise ValueError("--max-frames must be positive")
    if args.max_pixels < 1:
        raise ValueError("--max-pixels must be positive")
    if args.max_new_tokens < 1:
        raise ValueError("--max-new-tokens must be positive")

    groups = discover_trajectory_groups(args.rollout_dir)
    if args.trajectory_id is not None:
        groups = {
            trajectory_id: files
            for trajectory_id, files in groups.items()
            if trajectory_id == str(args.trajectory_id)
        }
        if not groups:
            raise ValueError(f"Trajectory {args.trajectory_id!r} was not found in replay NPZ files")
    if args.limit_trajectories is not None:
        groups = dict(list(sorted(groups.items()))[: args.limit_trajectories])

    dataset_dir = resolve_dataset_directory(
        args.rollout_dir, args.dataset_root_path, args.dataset_name
    )
    run_dir = _prepare_run_directory(args)
    sampling_configuration = _sampling_configuration(args)
    processor_configuration = _processor_configuration(args)
    config: dict[str, Any] = {
        "evaluation": "Ctrl-World replay trajectory success classification",
        "input_dir": str(resolve_evaluation_data_dir(args.rollout_dir)),
        "dataset_dir": str(dataset_dir),
        "annotation_split": "val",
        "model_name": args.model,
        "requested_model_revision": args.model_revision,
        "model_revision": None,
        "prompt_version": PROMPT_VERSION,
        "frame_sampling": sampling_configuration,
        "processor_settings": processor_configuration,
        "generation": {
            "do_sample": False,
            "max_new_tokens": args.max_new_tokens,
            "max_parse_retries": args.max_parse_retries,
        },
        "label_mapping": {"0": "failure", "1": "success"},
        "uncertain_convention": "Prediction-side abstention; DROID ground truth remains binary.",
        "cuda_required": True,
        "run_id": run_dir.name,
    }

    previous_records = (
        _load_resume_records(run_dir) if args.resume_run is not None else []
    )
    previous_by_id = _records_by_id(previous_records)
    records: dict[str, dict[str, Any]] = {}
    plans: dict[str, tuple[TrajectoryPlan, DroidAnnotation, list[tuple[str, str]]]] = {}

    for trajectory_id, files in sorted(groups.items()):
        annotation = load_droid_annotation(dataset_dir, trajectory_id)
        record = _make_record(trajectory_id, files, annotation, args.model, None)
        record["frame_sampling_configuration"] = sampling_configuration
        if annotation.status != "valid":
            record["reconstruction_status"] = "not_checked"
            records[trajectory_id] = record
            continue
        try:
            plan = inspect_trajectory(files, trajectory_id, annotation.video_length or 0)
            source_hashes = [(str(path.resolve()), sha256_file(path)) for path in plan.source_npz_files]
            record.update(
                {
                    "reconstruction_status": "valid",
                    "source_frame_count": plan.frame_count,
                    "source_frame_range": [
                        plan.frame_indices[0],
                        plan.frame_indices[-1],
                    ],
                    "source_frame_step": plan.source_step,
                    "camera_count": plan.camera_count,
                    "fps": plan.fps,
                    "frame_sampling_configuration": sampling_configuration,
                    "error_reason": None,
                }
            )
            records[trajectory_id] = record
            plans[trajectory_id] = (plan, annotation, source_hashes)
        except (OSError, ValueError, TrajectoryUnavailableError) as exc:
            record.update(
                {
                    "reconstruction_status": "unavailable",
                    "inference_status": "not_run",
                    "error_reason": str(exc),
                    "frame_sampling_configuration": sampling_configuration,
                }
            )
            records[trajectory_id] = record

    model_revision: str | None = None
    if plans:
        try:
            model_revision = resolve_model_revision(
                args.model, args.model_revision, args.local_files_only
            )
            config["model_revision"] = model_revision
        except Exception as exc:
            error = f"Could not resolve Qwen3-VL model revision: {type(exc).__name__}: {exc}"
            for trajectory_id in plans:
                record = records[trajectory_id]
                record.update(
                    {
                        "model_revision": args.model_revision,
                        "inference_status": "failed",
                        "error_reason": error,
                    }
                )
            write_evaluation_outputs(run_dir, config, list(records.values()))
            return run_dir, summarize_predictions(list(records.values()))[0]

    pending: list[str] = []
    for trajectory_id, (plan, annotation, source_hashes) in plans.items():
        cache_identity = build_cache_identity(
            trajectory_id,
            source_hashes,
            annotation.sha256,
            annotation.instruction or "",
            int(annotation.ground_truth_success),
            args.model,
            model_revision or args.model_revision or "main",
            sampling_configuration,
            processor_configuration,
            args.max_new_tokens,
            args.max_parse_retries,
        )
        record = records[trajectory_id]
        record["cache_identity"] = cache_identity
        record["model_revision"] = model_revision
        cached = (
            None
            if args.force
            else find_cached_prediction([previous_by_id.get(trajectory_id, {})], cache_identity)
        )
        if cached is not None:
            records[trajectory_id] = cached
        else:
            pending.append(trajectory_id)

    model = processor = None
    load_error = None
    if pending:
        try:
            model, processor, loaded_revision = load_vlm(
                args.model, model_revision or "main", args.local_files_only
            )
            model_revision = loaded_revision
            config["model_revision"] = loaded_revision
            for trajectory_id in pending:
                records[trajectory_id]["model_revision"] = loaded_revision
        except Exception as exc:
            load_error = f"Could not load Qwen3-VL: {type(exc).__name__}: {exc}"

    for trajectory_id in pending:
        record = records[trajectory_id]
        if load_error is not None:
            record.update({"inference_status": "failed", "error_reason": load_error})
            continue
        plan = plans[trajectory_id][0]
        try:
            reconstructed = reconstruct_prediction_trajectory(plan)
            images, sampled_source_indices = prepare_sampled_images(
                reconstructed,
                args.sampling_fps,
                args.max_frames,
                args.max_pixels,
            )
            result = judge_prediction(
                model,
                processor,
                record["instruction"],
                images,
                args.max_new_tokens,
                args.max_parse_retries,
            )
            record.update(
                {
                    **result,
                    "inference_status": "completed",
                    "error_reason": None,
                    "sampled_frame_count": len(images),
                    "sampled_source_frame_indices": sampled_source_indices,
                    "reconstructed_prediction_video_path": None,
                    "evaluation_timestamp": _utc_now(),
                }
            )
        except Exception as exc:
            record.update(
                {
                    "predicted_label": None,
                    "confidence": None,
                    "reasoning": None,
                    "inference_status": "failed",
                    "error_reason": f"{type(exc).__name__}: {exc}",
                    "evaluation_timestamp": _utc_now(),
                }
            )
        write_evaluation_outputs(run_dir, config, list(records.values()))

    summary = write_evaluation_outputs(run_dir, config, list(records.values()))
    return run_dir, summary


def main(argv: list[str] | None = None) -> int:
    args = _build_parser().parse_args(argv)
    run_dir, summary = run_evaluation(args)
    print(f"VLM replay evaluation written to {run_dir}")
    print(
        "Eligible binary classifications: "
        f"{summary['eligible_trajectories']}; "
        f"uncertain: {summary['uncertain_vlm_predictions']}; "
        f"failed inferences: {summary['failed_inferences']}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
