def _validation_report(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    report = []
    for record in records:
        for field, stage in (
            ("annotation_status", "annotation"),
            ("reconstruction_status", "reconstruction"),
            ("inference_status", "inference"),
        ):
            status = record.get(field)
            if status in ("missing", "invalid", "unavailable", "failed"):
                report.append(
                    {
                        "trajectory_id": record.get("trajectory_id"),
                        "stage": stage,
                        "status": status,
                        "reason": record.get("error_reason"),
                        "source_npz_files": record.get("source_npz_files", []),
                    }
                )
    return report


def _confusion_matrix(
    records: list[dict[str, Any]],
) -> tuple[dict[str, Any], dict[str, Any]]:
    usable = [
        record
        for record in records
        if record.get("ground_truth_success") in (0, 1)
        and record.get("inference_status") == "completed"
        and record.get("predicted_label") in PREDICTION_LABELS
    ]
    counts = {actual: {predicted: 0 for predicted in PREDICTION_LABELS} for actual in BINARY_LABELS}
    for record in usable:
        actual = "success" if record["ground_truth_success"] == 1 else "failure"
        counts[actual][record["predicted_label"]] += 1

    decided = [
        record for record in usable if record["predicted_label"] in BINARY_LABELS
    ]
    binary_counts = {actual: {predicted: 0 for predicted in BINARY_LABELS} for actual in BINARY_LABELS}
    for record in decided:
        actual = "success" if record["ground_truth_success"] == 1 else "failure"
        binary_counts[actual][record["predicted_label"]] += 1

    per_class: dict[str, dict[str, Any]] = {}
    class_f1: dict[str, float] = {}
    supports: dict[str, int] = {}
    for label in BINARY_LABELS:
        tp = binary_counts[label][label]
        fp = sum(binary_counts[other][label] for other in BINARY_LABELS if other != label)
        support = sum(binary_counts[label].values())
        precision = tp / (tp + fp) if tp + fp else 0.0
        recall = tp / support if support else 0.0
        f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
        per_class[label] = {
            "precision": precision if decided else None,
            "recall": recall if decided else None,
            "f1": f1 if decided else None,
            "support": support,
        }
        class_f1[label] = f1
        supports[label] = support

    correct = sum(
        record["ground_truth_success"] == int(record["predicted_label"] == "success")
        for record in decided
    )
    incorrect = len(decided) - correct
    binary_metrics = {
        "eligible_trajectories": len(decided),
        "correctly_classified": correct,
        "incorrectly_classified": incorrect,
        "excluded_from_binary_metrics": len(records) - len(decided),
        "uncertain_predictions_excluded": sum(
            record.get("ground_truth_success") in (0, 1)
            and record.get("inference_status") == "completed"
            and record.get("predicted_label") == "uncertain"
            for record in records
        ),
        "accuracy": correct / len(decided) if decided else None,
        "precision_success": per_class["success"]["precision"],
        "recall_success": per_class["success"]["recall"],
        "f1_success": per_class["success"]["f1"],
        "macro_f1": (
            sum(class_f1.values()) / len(BINARY_LABELS) if decided else None
        ),
        "weighted_f1": (
            sum(class_f1[label] * supports[label] for label in BINARY_LABELS) / len(decided)
            if decided
            else None
        ),
        "per_class": per_class,
        "confusion_matrix": {
            "labels": list(BINARY_LABELS),
            "rows_actual_columns_predicted": [
                [binary_counts[label][prediction] for prediction in BINARY_LABELS]
                for label in BINARY_LABELS
            ],
        },
    }

    outcome_matrix = {
        "ground_truth_labels": list(BINARY_LABELS),
        "prediction_outcomes": list(PREDICTION_LABELS),
        "rows_actual_columns_predicted": [
            [counts[label][prediction] for prediction in PREDICTION_LABELS]
            for label in BINARY_LABELS
        ],
        "convention": (
            "UNCERTAIN is a prediction-side abstention outcome. DROID annotations remain "
            "binary; there is no ground-truth uncertain class."
        ),
        "per_outcome_counts": {
            outcome: sum(counts[actual][outcome] for actual in BINARY_LABELS)
            for outcome in PREDICTION_LABELS
        },
    }
    return binary_metrics, outcome_matrix


def summarize_predictions(records: list[dict[str, Any]]) -> tuple[dict[str, Any], dict[str, Any]]:
    binary_metrics, outcome_matrix = _confusion_matrix(records)
    valid_ground_truth = [
        record for record in records if record.get("ground_truth_success") in (0, 1)
    ]
    completed = [
        record for record in records if record.get("inference_status") == "completed"
    ]
    total = len(records)
    success_count = sum(record["ground_truth_success"] == 1 for record in valid_ground_truth)
    predicted_counts = {
        label: sum(record.get("predicted_label") == label for record in completed)
        for label in PREDICTION_LABELS
    }
    summary = {
        "total_trajectories": total,
        "ground_truth_labels_available": len(valid_ground_truth),
        "eligible_trajectories": binary_metrics["eligible_trajectories"],
        "correctly_classified": binary_metrics["correctly_classified"],
        "incorrectly_classified": binary_metrics["incorrectly_classified"],
        "uncertain_vlm_predictions": predicted_counts["uncertain"],
        "missing_annotations": sum(record.get("annotation_status") == "missing" for record in records),
        "invalid_annotations": sum(record.get("annotation_status") == "invalid" for record in records),
        "failed_inferences": sum(record.get("inference_status") == "failed" for record in records),
        "unavailable_reconstructions": sum(
            record.get("reconstruction_status") == "unavailable" for record in records
        ),
        "excluded_from_binary_metrics": binary_metrics["excluded_from_binary_metrics"],
        "binary_classification_metrics": binary_metrics,
        "success_rate_comparison": {
            "original_droid": {
                "success_count": success_count,
                "denominator": len(valid_ground_truth),
                "rate": success_count / len(valid_ground_truth) if valid_ground_truth else None,
            },
            "vlm_predictions": {
                "denominator": len(completed),
                "success_count": predicted_counts["success"],
                "failure_count": predicted_counts["failure"],
                "uncertain_count": predicted_counts["uncertain"],
                "success_rate": (
                    predicted_counts["success"] / len(completed) if completed else None
                ),
                "failure_rate": (
                    predicted_counts["failure"] / len(completed) if completed else None
                ),
                "uncertain_rate": (
                    predicted_counts["uncertain"] / len(completed) if completed else None
                ),
            },
            "warning": (
                "The VLM-predicted success rate is not ground-truth task performance; "
                "classification accuracy is reported separately."
            ),
        },
        "three_outcome_evaluation": outcome_matrix,
        "three_outcome_metrics": {
            "prediction_coverage": (
                (predicted_counts["success"] + predicted_counts["failure"]) / len(completed)
                if completed
                else None
            ),
            "selective_accuracy": binary_metrics["accuracy"],
            "uncertain_rate": (
                predicted_counts["uncertain"] / len(completed) if completed else None
            ),
            "note": (
                "Standard three-class F1 is not defined because DROID supplies no "
                "ground-truth uncertain class. The matrix treats uncertainty as abstention."
            ),
        },
    }
    confusion = {
        "binary_decisions": binary_metrics["confusion_matrix"],
        "three_outcome_abstention_matrix": outcome_matrix,
    }
    return summary, confusion


def write_evaluation_outputs(
    run_dir: Path, config: dict[str, Any], records: list[dict[str, Any]]
) -> dict[str, Any]:
    ordered = sorted(records, key=lambda record: str(record.get("trajectory_id", "")))
    summary, confusion = summarize_predictions(ordered)
    write_json(run_dir / "config.json", config)
    write_json(run_dir / "predictions.json", ordered)
    write_csv(run_dir / "predictions.csv", ordered)
    write_json(run_dir / "summary.json", summary)
    write_json(run_dir / "confusion_matrix.json", confusion)
    validation_report = _validation_report(ordered)
    write_json(run_dir / "validation_report.json", validation_report)
    return summary


