JUDGING_PROMPT = """You are evaluating a robot manipulation trajectory generated by a world model.

You will receive:

1. A natural-language instruction describing the task.
2. A chronological sequence of sampled images from the generated execution. Each image shows
   synchronized camera views labeled by camera.
Determine whether the generated sequence demonstrates successful completion of the requested task.

Evaluate the complete sampled sequence and visual outcome, not merely the robot's attempt to perform the action.

Return SUCCESS when the video provides sufficient visual evidence that the requested task has been completed.

Return FAILURE when the video demonstrates that the requested task was not completed.

Return UNCERTAIN when the video is ambiguous, incomplete, heavily occluded, or does not provide sufficient evidence for a reliable decision.

Do not assume success simply because the robot moved toward the target.

Do not judge using the task instruction alone.

Do not invent events that are not visible.

Pay attention to the temporal progression and final state.

Provide a concise explanation based only on the generated images.

Return exactly one JSON object with keys "prediction", "confidence", and "reasoning"."""

PREDICTION_LABELS = ("failure", "success", "uncertain")
BINARY_LABELS = ("failure", "success")


class TrajectoryUnavailableError(ValueError):
    """Raised when saved interactions cannot reliably form a full trajectory."""


@dataclass(frozen=True)
class DroidAnnotation:
    status: str
    annotation_path: str | None
    instruction: str | None
    ground_truth_success: int | None
    video_length: int | None
    sha256: str | None
    reason: str | None

    @property
    def ground_truth_label(self) -> str | None:
        if self.ground_truth_success is None:
            return None
        return "success" if self.ground_truth_success == 1 else "failure"


@dataclass(frozen=True)
class InteractionPlan:
    path: Path
    trajectory_id: str
    interaction_index: int
    start_frame_index: int
    fps: float
    frame_indices: tuple[int, ...]
    canonical_shape: tuple[int, int, int, int, int]


@dataclass(frozen=True)
class TrajectoryPlan:
    trajectory_id: str
    interactions: tuple[InteractionPlan, ...]
    fps: float
    frame_indices: tuple[int, ...]
    frame_count: int
    camera_count: int
    height: int
    width: int
    source_step: int

    @property
    def source_npz_files(self) -> list[Path]:
        return [interaction.path for interaction in self.interactions]


@dataclass(frozen=True)
class ReconstructedTrajectory:
    frames: np.ndarray
    source_frame_indices: np.ndarray
    fps: float


def _utc_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _scalar(archive: Any, key: str) -> Any:
    if key not in archive:
        raise ValueError(f"NPZ metadata field {key!r} is missing")
    value = np.asarray(archive[key])
    if value.size != 1:
        raise ValueError(f"NPZ metadata field {key!r} must be scalar, got {value.shape}")
    result = value.reshape(()).item()
    if isinstance(result, bytes):
        result = result.decode("utf-8")
    return result


def _integer(value: Any, field: str) -> int:
    if isinstance(value, (bool, np.bool_)):
        raise ValueError(f"{field} must be an integer")
    try:
        result = int(value)
        if float(value) != result:
            raise ValueError
    except (TypeError, ValueError, OverflowError) as exc:
        raise ValueError(f"{field} must be an integer, got {value!r}") from exc
    return result


def _canonical_prediction(array: np.ndarray, source: Path) -> np.ndarray:
    """Normalize a replay prediction to time,camera,height,width,RGB."""
    prediction = np.asarray(array)
    if prediction.ndim == 5:
        camera_count, frame_count, height, width, channels = prediction.shape
        prediction = prediction.transpose(1, 0, 2, 3, 4)
    elif prediction.ndim == 4:
        frame_count, height, width, channels = prediction.shape
        camera_count = 1
        prediction = prediction[:, np.newaxis, ...]
    else:
        raise ValueError(
            f"Prediction in {source} must be camera,time,H,W,C or time,H,W,C; "
            f"got {prediction.shape}"
        )
    if min(camera_count, frame_count, height, width) < 1 or channels not in (1, 3, 4):
        raise ValueError(f"Unsupported prediction shape in {source}: {prediction.shape}")
    if not (
        np.issubdtype(prediction.dtype, np.integer)
        or np.issubdtype(prediction.dtype, np.floating)
    ) or not np.isfinite(prediction).all():
        raise ValueError(f"Prediction in {source} must contain finite real-valued pixels")
    if np.issubdtype(prediction.dtype, np.floating):
        minimum = float(prediction.min())
        maximum = float(prediction.max())
        if minimum < 0:
            raise ValueError(f"Prediction pixels in {source} must be non-negative")
        if maximum <= 1:
            prediction = prediction * 255
    if float(prediction.min()) < 0 or float(prediction.max()) > 255:
        raise ValueError(f"Prediction pixels in {source} must fit [0,255]")
    if channels == 1:
        prediction = np.repeat(prediction, 3, axis=-1)
    elif channels == 4:
        prediction = prediction[..., :3]
    return prediction.astype(np.uint8, copy=False)


def _inspect_interaction(path: Path, expected_trajectory_id: str) -> InteractionPlan:
    try:
        with np.load(path, allow_pickle=False) as archive:
            trajectory_id = str(_scalar(archive, "trajectory_id")).strip()
            interaction_index = _integer(_scalar(archive, "interaction_index"), "interaction_index")
            start_frame_index = _integer(_scalar(archive, "start_frame_index"), "start_frame_index")
            fps = float(_scalar(archive, "fps"))
            if not math.isfinite(fps) or fps <= 0:
                raise ValueError(f"FPS must be finite and positive in {path}")
            indices_array = np.asarray(archive["frame_indices"])
            if indices_array.ndim != 1 or not (
                np.issubdtype(indices_array.dtype, np.integer)
                or np.issubdtype(indices_array.dtype, np.floating)
            ):
                raise ValueError(f"frame_indices in {path} must be a one-dimensional numeric array")
            if not np.isfinite(indices_array).all() or not np.equal(
                indices_array, np.floor(indices_array)
            ).all():
                raise ValueError(f"frame_indices in {path} must contain integers")
            frame_indices = tuple(int(index) for index in indices_array)
            prediction = _canonical_prediction(np.asarray(archive["prediction"]), path)
    except (OSError, EOFError, KeyError, TypeError, ValueError) as exc:
        raise TrajectoryUnavailableError(f"Could not inspect {path}: {exc}") from exc

    if trajectory_id != expected_trajectory_id:
        raise TrajectoryUnavailableError(
            f"{path} identifies trajectory {trajectory_id!r}, expected "
            f"{expected_trajectory_id!r}"
        )
    if interaction_index < 0 or start_frame_index < 0:
        raise TrajectoryUnavailableError(f"Negative interaction or source-frame index in {path}")
    if len(frame_indices) != prediction.shape[0]:
        raise TrajectoryUnavailableError(
            f"{path} has {len(frame_indices)} source indices for "
            f"{prediction.shape[0]} prediction frames"
        )
    if not frame_indices or any(index < 0 for index in frame_indices):
        raise TrajectoryUnavailableError(f"Invalid frame_indices in {path}")
    if any(right < left for left, right in zip(frame_indices, frame_indices[1:])):
        raise TrajectoryUnavailableError(f"frame_indices are not chronological in {path}")

    return InteractionPlan(
        path=path,
        trajectory_id=trajectory_id,
        interaction_index=interaction_index,
        start_frame_index=start_frame_index,
        fps=fps,
        frame_indices=frame_indices,
        canonical_shape=tuple(int(value) for value in prediction.shape),
    )


def inspect_trajectory(
    npz_files: list[Path] | tuple[Path, ...],
    trajectory_id: str,
    video_length: int,
) -> TrajectoryPlan:
    """Validate metadata, overlap boundaries, and full source-frame coverage."""
    if not npz_files:
        raise TrajectoryUnavailableError("No interaction NPZ files were found")
    if isinstance(video_length, bool) or type(video_length) is not int or video_length < 1:
        raise TrajectoryUnavailableError("Annotation video_length must be a positive integer")

    interactions = [
        _inspect_interaction(Path(path), trajectory_id) for path in npz_files
    ]
    interactions.sort(key=lambda item: (item.interaction_index, item.start_frame_index, str(item.path)))
    interaction_ids = [item.interaction_index for item in interactions]
    if interaction_ids != list(range(len(interactions))):
        raise TrajectoryUnavailableError(
            "Interaction indices must be complete and consecutive starting at zero; "
            f"found {interaction_ids}"
        )
    fps_values = {item.fps for item in interactions}
    if len(fps_values) != 1:
        raise TrajectoryUnavailableError(f"Interaction FPS metadata is inconsistent: {sorted(fps_values)}")
    if any(
        current.start_frame_index < previous.start_frame_index
        for previous, current in zip(interactions, interactions[1:])
    ):
        raise TrajectoryUnavailableError("Interaction start_frame_index values are not chronological")
    expected_shape = interactions[0].canonical_shape[1:]
    if any(item.canonical_shape[1:] != expected_shape for item in interactions):
        raise TrajectoryUnavailableError("Prediction camera or image dimensions change between interactions")

    for previous, current in zip(interactions, interactions[1:]):
        if previous.frame_indices[-1] != current.frame_indices[0]:
            raise TrajectoryUnavailableError(
                "Adjacent interactions do not share the replay boundary source frame "
                f"({previous.frame_indices[-1]} != {current.frame_indices[0]})"
            )
    if any(
        index >= video_length
        for interaction in interactions
        for index in interaction.frame_indices
    ):
        raise TrajectoryUnavailableError(
            f"Source-frame indices exceed annotation video_length={video_length}"
        )

    # Match the replay writer: drop each non-final chunk's last overlapping frame.
    assembled_indices: list[int] = []
    for position, interaction in enumerate(interactions):
        chunk_indices = (
            interaction.frame_indices[:-1]
            if position < len(interactions) - 1
            else interaction.frame_indices
        )
        assembled_indices.extend(chunk_indices)

    if not assembled_indices or assembled_indices[0] != 0:
        raise TrajectoryUnavailableError(
            "Replay does not begin at source frame zero; the original trajectory is incomplete"
        )
    if assembled_indices[-1] != video_length - 1:
        raise TrajectoryUnavailableError(
            "Replay does not reach the annotation's final source frame "
            f"{video_length - 1}; reached {assembled_indices[-1]}"
        )
    positive_steps = [
        right - left
        for left, right in zip(assembled_indices, assembled_indices[1:])
        if right > left
    ]
    source_step = min(positive_steps) if positive_steps else 1
    for left, right in zip(assembled_indices, assembled_indices[1:]):
        difference = right - left
        if difference < 0 or (difference > 0 and difference != source_step):
            raise TrajectoryUnavailableError(
                f"Source-frame gap or ordering conflict between {left} and {right}"
            )
        if difference == 0 and left != video_length - 1:
            raise TrajectoryUnavailableError(
                f"Repeated source frame {left} occurs before the trajectory endpoint"
            )

    first_shape = interactions[0].canonical_shape
    return TrajectoryPlan(
        trajectory_id=trajectory_id,
        interactions=tuple(interactions),
        fps=interactions[0].fps,
        frame_indices=tuple(assembled_indices),
        frame_count=len(assembled_indices),
        camera_count=first_shape[1],
        height=first_shape[2],
        width=first_shape[3],
        source_step=source_step,
    )


def reconstruct_prediction_trajectory(plan: TrajectoryPlan) -> ReconstructedTrajectory:
    """Rebuild the replay video from prediction arrays only."""
    frame_chunks: list[np.ndarray] = []
    frame_indices: list[int] = []
    for position, interaction in enumerate(plan.interactions):
        try:
            with np.load(interaction.path, allow_pickle=False) as archive:
                frames = _canonical_prediction(np.asarray(archive["prediction"]), interaction.path)
        except (OSError, EOFError, KeyError, ValueError) as exc:
            raise TrajectoryUnavailableError(
                f"Could not load prediction frames from {interaction.path}: {exc}"
            ) from exc
        if tuple(int(value) for value in frames.shape) != interaction.canonical_shape:
            raise TrajectoryUnavailableError(
                f"Prediction shape changed after inspection in {interaction.path}"
            )
        if position < len(plan.interactions) - 1:
            frames = frames[:-1]
            indices = interaction.frame_indices[:-1]
        else:
            indices = interaction.frame_indices
        if len(frames):
            frame_chunks.append(frames)
            frame_indices.extend(indices)

    if not frame_chunks:
        raise TrajectoryUnavailableError("No prediction frames remain after boundary reconstruction")
    result = np.concatenate(frame_chunks, axis=0)
    if result.shape[0] != len(plan.frame_indices) or tuple(frame_indices) != plan.frame_indices:
        raise TrajectoryUnavailableError("Reconstructed frames do not match validated source-frame order")
    return ReconstructedTrajectory(
        frames=result,
        source_frame_indices=np.asarray(frame_indices, dtype=np.int64),
        fps=plan.fps,
    )


def sample_frame_positions(
    frame_count: int,
    fps: float,
    sampling_fps: float = 5.0,
    max_frames: int = 50,
) -> list[int]:
    if frame_count < 1 or not math.isfinite(fps) or fps <= 0:
        raise ValueError("A positive frame count and FPS are required")
    if not math.isfinite(sampling_fps) or sampling_fps <= 0 or max_frames < 1:
        raise ValueError("sampling_fps and max_frames must be positive")
    duration = (frame_count - 1) / fps
    requested_count = max(1, math.ceil(duration * sampling_fps) + 1)
    selected_count = min(frame_count, max_frames, requested_count)
    positions = np.rint(np.linspace(0, frame_count - 1, selected_count)).astype(int)
    return sorted(set(int(position) for position in positions) | {frame_count - 1})


def resize_to_pixel_budget(image: Image.Image, max_pixels: int) -> Image.Image:
    if max_pixels < 1:
        raise ValueError("max_pixels must be positive")
    width, height = image.size
    if width * height <= max_pixels:
        return image
    scale = math.sqrt(max_pixels / (width * height))
    size = (max(1, int(width * scale)), max(1, int(height * scale)))
    return image.resize(size, Image.Resampling.LANCZOS)


def compose_prediction_camera_grid(
    camera_frames: np.ndarray, max_pixels: int
) -> Image.Image:
    """Compose synchronized prediction views into one labeled image."""
    frames = np.asarray(camera_frames)
    if frames.ndim != 4 or frames.shape[-1] != 3 or frames.shape[0] < 1:
        raise ValueError(f"Expected camera,height,width,RGB frames, got {frames.shape}")
    camera_count, height, width, _ = frames.shape
    label_height = max(20, min(36, height // 8))
    columns = math.ceil(math.sqrt(camera_count))
    rows = math.ceil(camera_count / columns)
    canvas = Image.new("RGB", (columns * width, rows * (height + label_height)), "black")
    draw = ImageDraw.Draw(canvas)
    for camera_index, frame in enumerate(frames):
        x = (camera_index % columns) * width
        y = (camera_index // columns) * (height + label_height)
        image = Image.fromarray(frame.astype(np.uint8, copy=False), mode="RGB")
        canvas.paste(image, (x, y + label_height))
        draw.rectangle((x, y, x + width, y + label_height), fill="black")
        draw.text((x + 5, y + 3), f"Camera {camera_index}", fill="white")
    return resize_to_pixel_budget(canvas, max_pixels)


def prepare_sampled_images(
    trajectory: ReconstructedTrajectory,
    sampling_fps: float,
    max_frames: int,
    max_pixels: int,
) -> tuple[list[Image.Image], list[int]]:
    positions = sample_frame_positions(
        len(trajectory.frames), trajectory.fps, sampling_fps, max_frames
    )
    images = [
        compose_prediction_camera_grid(trajectory.frames[position], max_pixels)
        for position in positions
    ]
    source_indices = [
        int(trajectory.source_frame_indices[position]) for position in positions
    ]
    return images, source_indices


def resolve_evaluation_data_dir(rollout_dir: str | Path) -> Path:
    root = Path(rollout_dir).expanduser().resolve()
    if not root.is_dir():
        raise FileNotFoundError(f"Replay output directory does not exist: {root}")
    if root.name == "evaluation_data":
        return root
    nested = root / "evaluation_data"
    return nested if nested.is_dir() else root


def discover_trajectory_groups(rollout_dir: str | Path) -> dict[str, list[Path]]:
    root = resolve_evaluation_data_dir(rollout_dir)
    files = sorted(path for path in root.rglob("*.npz") if path.is_file())
    if not files:
        raise FileNotFoundError(f"No replay interaction NPZ files found under {root}")
    grouped: dict[str, list[Path]] = {}
    for path in files:
        trajectory_directory = next(
            (parent for parent in path.parents if parent.name.startswith("trajectory_")),
            None,
        )
        if trajectory_directory is not None:
            trajectory_id = trajectory_directory.name[len("trajectory_") :]
        else:
            try:
                with np.load(path, allow_pickle=False) as archive:
                    trajectory_id = str(_scalar(archive, "trajectory_id")).strip()
            except (OSError, EOFError, KeyError, TypeError, ValueError):
                trajectory_id = f"unidentified:{path.relative_to(root)}"
        if not trajectory_id:
            trajectory_id = f"unidentified:{path.relative_to(root)}"
        grouped.setdefault(trajectory_id, []).append(path)
    return grouped


def load_droid_annotation(dataset_dir: str | Path, trajectory_id: str) -> DroidAnnotation:
    """Read task instruction and binary success only from the DROID annotation."""
    dataset_root = Path(dataset_dir)
    annotation_path = _resolve_annotation(dataset_root, trajectory_id)
    if annotation_path is None:
        expected = dataset_root / "annotation" / "val" / f"{trajectory_id}.json"
        return DroidAnnotation(
            "missing", str(expected), None, None, None, None,
            f"No unique DROID annotation found for trajectory {trajectory_id!r}",
        )
    try:
        raw_bytes = annotation_path.read_bytes()
        digest = hashlib.sha256(raw_bytes).hexdigest()
        data = json.loads(raw_bytes.decode("utf-8"))
        if not isinstance(data, dict):
            raise ValueError("Annotation root must be a JSON object")

        errors: list[str] = []
        success_value = data.get("success")
        if isinstance(success_value, bool):
            success = int(success_value)
        elif type(success_value) is int and success_value in (0, 1):
            success = success_value
        else:
            success = None
            errors.append("Annotation success must be a boolean or integer 0/1")

        texts = data.get("texts")
        if not isinstance(texts, list) or not texts or not isinstance(texts[0], str):
            instruction = None
            errors.append("Annotation texts[0] must be a task-instruction string")
        else:
            instruction = texts[0].strip()
            if not instruction:
                instruction = None
                errors.append("Annotation texts[0] is empty")

        length_value = data.get("video_length")
        if isinstance(length_value, bool) or type(length_value) is not int or length_value < 1:
            video_length = None
            errors.append("Annotation video_length must be a positive integer")
        else:
            video_length = length_value
        if errors:
            return DroidAnnotation(
                "invalid",
                str(annotation_path.resolve()),
                instruction,
                success,
                video_length,
                digest,
                "Invalid DROID annotation: " + "; ".join(errors),
            )
        return DroidAnnotation(
            "valid",
            str(annotation_path.resolve()),
            instruction,
            success,
            video_length,
            digest,
            None,
        )
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        try:
            digest = sha256_file(annotation_path) if annotation_path.is_file() else None
        except OSError:
            digest = None
        return DroidAnnotation(
            "invalid",
            str(annotation_path.resolve()),
            None,
            None,
            None,
            digest,
            f"Invalid DROID annotation: {exc}",
        )


def sha256_file(path: str | Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def build_cache_identity(
    trajectory_id: str,
    source_hashes: list[tuple[str, str]],
    annotation_sha256: str | None,
    instruction: str,
    ground_truth_success: int,
    model_name: str,
    model_revision: str,
    sampling_configuration: dict[str, Any],
    processor_configuration: dict[str, Any],
    max_new_tokens: int,
    max_parse_retries: int = 0,
) -> str:
    payload = {
        "trajectory_id": trajectory_id,
        "source_npz_sha256": sorted(source_hashes),
        "annotation_sha256": annotation_sha256,
        "instruction": instruction,
        "ground_truth_success": ground_truth_success,
        "model_name": model_name,
        "model_revision": model_revision,
        "prompt_version": PROMPT_VERSION,
        "prompt_sha256": hashlib.sha256(JUDGING_PROMPT.encode("utf-8")).hexdigest(),
        "sampling_configuration": sampling_configuration,
        "processor_configuration": processor_configuration,
        "generation_configuration": {
            "do_sample": False,
            "max_new_tokens": max_new_tokens,
            "max_parse_retries": max_parse_retries,
        },
    }
    encoded = json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def find_cached_prediction(
    records: list[dict[str, Any]], cache_identity: str
) -> dict[str, Any] | None:
    for record in records:
        if (
            record.get("cache_identity") == cache_identity
            and record.get("inference_status") == "completed"
            and record.get("predicted_label") in PREDICTION_LABELS
        ):
            return record
    return None


def parse_vlm_json(text: str) -> dict[str, Any]:
    response = text.strip()
    if response.startswith("```") and response.endswith("```"):
        response = response[3:-3].strip()
        if response.lower().startswith("json"):
            response = response[4:].strip()
    try:
        value = json.loads(response)
    except json.JSONDecodeError as exc:
        raise ValueError(f"VLM response is not valid JSON: {exc}") from exc
    if not isinstance(value, dict):
        raise ValueError("VLM JSON response must be an object")
    prediction = value.get("prediction")
    if not isinstance(prediction, str) or prediction.strip().lower() not in PREDICTION_LABELS:
        raise ValueError("VLM prediction must be success, failure, or uncertain")
    confidence = value.get("confidence")
    if (
        isinstance(confidence, bool)
        or not isinstance(confidence, (int, float))
        or not math.isfinite(float(confidence))
        or not 0 <= float(confidence) <= 1
    ):
        raise ValueError("VLM confidence must be a finite number between 0 and 1")
    reasoning = value.get("reasoning")
    if not isinstance(reasoning, str) or not reasoning.strip():
        raise ValueError("VLM reasoning must be a non-empty string")
    return {
        "predicted_label": prediction.strip().lower(),
        "confidence": float(confidence),
        "reasoning": reasoning.strip(),
    }


def build_vlm_messages(instruction: str, images: list[Image.Image]) -> list[dict[str, Any]]:
    content: list[dict[str, Any]] = [
        {
            "type": "text",
            "text": (
                f"Task instruction: {instruction}\n"
                "The following synchronized camera-grid images are sampled in chronological "
                "order from the generated prediction sequence. Each tile is labeled by camera. "
                "Judge only the generated sequence."
            ),
        }
    ]
    content.extend({"type": "image", "image": image} for image in images)
    return [
        {"role": "system", "content": JUDGING_PROMPT},
        {"role": "user", "content": content},
    ]


def judge_with_retries(
    instruction: str,
    images: list[Image.Image],
    generate: Callable[[list[dict[str, Any]]], str],
    max_retries: int,
) -> dict[str, Any]:
    if max_retries < 0:
        raise ValueError("max_retries cannot be negative")
    messages = build_vlm_messages(instruction, images)
    for attempt in range(max_retries + 1):
        response = generate(messages)
        try:
            result = parse_vlm_json(response)
            result["attempt_count"] = attempt + 1
            return result
        except ValueError as exc:
            if attempt >= max_retries:
                raise ValueError(
                    f"VLM returned invalid structured output after {attempt + 1} attempts: {exc}"
                ) from exc
            messages.extend(
                [
                    {"role": "assistant", "content": response},
                    {
                        "role": "user",
                        "content": (
                            "The previous response did not satisfy the required JSON schema. "
                            "Return only a valid JSON object with prediction, confidence, and "
                            "reasoning, using the same visual evidence."
                        ),
                    },
                ]
            )
    raise AssertionError("unreachable")


def _require_transformers() -> Any:
    try:
        import transformers
        from packaging.version import Version
    except ImportError as exc:
        raise RuntimeError(
            "Qwen3-VL requires Hugging Face Transformers >=4.57.0. "
            "Install the optional dependencies from eval/requirements_vlm.txt."
        ) from exc
    current = Version(transformers.__version__)
    minimum = Version(MIN_TRANSFORMERS_VERSION)
    if current < minimum:
        raise RuntimeError(
            f"Installed Transformers {current} does not include Qwen3-VL support; "
            f"version {minimum} or newer is required. The repository's main "
            "requirements.txt currently pins Transformers 4.48.1."
        )
    if current.major >= 5:
        raise RuntimeError(
            f"Transformers {current} is outside the verified <5 range; "
            "use eval/requirements_vlm.txt."
        )
    return transformers


def resolve_model_revision(
    model_name: str, requested_revision: str | None, local_files_only: bool
) -> str:
    transformers = _require_transformers()
    config = transformers.AutoConfig.from_pretrained(
        model_name,
        revision=requested_revision,
        local_files_only=local_files_only,
    )
    resolved = getattr(config, "_commit_hash", None)
    return str(resolved or requested_revision or "main")


def load_vlm(
    model_name: str,
    model_revision: str,
    local_files_only: bool,
) -> tuple[Any, Any, str]:
    transformers = _require_transformers()
    try:
        import torch
    except ImportError as exc:
        raise RuntimeError("Local Qwen3-VL inference requires PyTorch with CUDA support") from exc
    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is required for Qwen3-VL replay evaluation")

    dtype = (
        torch.bfloat16
        if torch.cuda.is_bf16_supported()
        else torch.float16
    )
    processor = transformers.AutoProcessor.from_pretrained(
        model_name,
        revision=model_revision,
        local_files_only=local_files_only,
    )
    model_class = getattr(transformers, "Qwen3VLForConditionalGeneration", None)
    if model_class is None:
        raise RuntimeError(
            "The installed Transformers build does not expose "
            "Qwen3VLForConditionalGeneration; install eval/requirements_vlm.txt."
        )
    model = model_class.from_pretrained(
        model_name,
        revision=model_revision,
        dtype=dtype,
        device_map="auto",
        attn_implementation="sdpa",
        low_cpu_mem_usage=True,
        local_files_only=local_files_only,
    )
    model.eval()
    resolved_revision = str(getattr(model.config, "_commit_hash", None) or model_revision)
    return model, processor, resolved_revision


def _generate_text(
    model: Any,
    processor: Any,
    messages: list[dict[str, Any]],
    max_new_tokens: int,
) -> str:
    try:
        import torch
    except ImportError as exc:
        raise RuntimeError("Local Qwen3-VL inference requires PyTorch") from exc
    inputs = processor.apply_chat_template(
        messages,
        tokenize=True,
        add_generation_prompt=True,
        return_dict=True,
        return_tensors="pt",
    )
    inputs.pop("token_type_ids", None)
    inputs = inputs.to(model.device)
    with torch.inference_mode():
        outputs = model.generate(**inputs, do_sample=False, max_new_tokens=max_new_tokens)
    output_ids = [
        output[len(input_ids) :]
        for input_ids, output in zip(inputs.input_ids, outputs)
    ]
    decoded = processor.batch_decode(
        output_ids,
        skip_special_tokens=True,
        clean_up_tokenization_spaces=False,
    )
    if not decoded:
        raise RuntimeError("Qwen3-VL returned no decoded response")
    return decoded[0]


